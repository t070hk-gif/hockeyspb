def main():
    failed = 0
    from datetime import datetime
    for case in CASES:
        title, dates, expected = case[:3]
        start = datetime.strptime(case[3], "%d.%m.%Y %H:%M") if len(case) > 3 else None
        want_age = case[4] if len(case) > 4 else None
        result, reason = tm.match_title(title, dates, fixtures=FIXTURES, start_dt=start)
        got = None if result is None else {result["team1"], result["team2"]}
        want = None if expected is None else set(expected)
        ok = got == want and (want_age is None or (result and result.get("age") == want_age))
        if not ok:
            failed += 1
        status = "OK  " if ok else "FAIL"
        got_txt = "—" if result is None else f'{result["team1"]} | {result["team2"]} ({result["date"]}, {result.get("age")})'
        print(f"[{status}] {title[:70]}")
        if not ok:
            print(f"        ожидалось: {expected}")
            print(f"        получено:  {got_txt}  [{reason}]")

    # Даты-кандидаты: опечатка в годе заголовка
    ts = datetime(2026, 10, 4, 11, 55).timestamp()
    for title, want in (("Невский 10 - СКА Петергоф 10, 12:00, 04.10.25", "04.10.2026"),
                        ("Невский 10 - СКА Петергоф 10, 12:00, 04.10.26", "04.10.2026"),
                        ("Невский 10 - СКА Петергоф 10", "04.10.2026")):
        got = tm.build_date_candidates(title, ts, ts)[0]
        ok = got == want
        failed += not ok
        print(f"[{'OK  ' if ok else 'FAIL'}] дата для «{title[-30:]}»: {got}")

    print()
    print(f"Итого: {len(CASES) + 3 - failed} из {len(CASES) + 3} прошло")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
